"""Worker cashbook statement as a PDF.

Built with ReportLab rather than WeasyPrint or pdfkit. Both of those render
HTML, which would have been the nicer authoring experience, but neither
installs cleanly here: WeasyPrint needs a system-wide GTK/Pango runtime on
Windows, and pdfkit shells out to the wkhtmltopdf binary, which is unmaintained
upstream. ReportLab is pure Python, so `pip install` is the whole setup.

FONTS AND DEVANAGARI
--------------------
The built-in Helvetica has no Devanagari glyphs, so a worker named "सुरेश"
would render as black boxes. Names are currently entered in Latin script, so
this is fine today. To support Devanagari, register a Unicode TTF once at
import and swap FONT_REGULAR/FONT_BOLD to it:

    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    pdfmetrics.registerFont(TTFont("NotoSans", "path/to/NotoSansDevanagari-Regular.ttf"))
"""

from datetime import date as date_type
from decimal import Decimal
from io import BytesIO
from typing import Optional

from reportlab.lib import colors
from reportlab.lib.enums import TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.models.attendance import Attendance
from app.models.cash import CashEntry
from app.models.enums import AttendanceStatus, TransactionType
from app.models.transaction import Transaction
from app.models.user import User
from app.models.invoice import Invoice
from app.models.site import Site
from app.schemas.cash import CashSummary, CategoryTotal
from app.schemas.invoice import InvoicePreview
from app.schemas.ledger import BalanceSummary

FONT_REGULAR = "Helvetica"
FONT_BOLD = "Helvetica-Bold"

# Matches the app's tint so a printed statement and the screen look related.
INK = colors.HexColor("#111111")
MUTED = colors.HexColor("#60646C")
RULE = colors.HexColor("#D8D8DE")
ACCENT = colors.HexColor("#0A7EA4")
POSITIVE = colors.HexColor("#1B873F")
NEGATIVE = colors.HexColor("#D93036")
BAND = colors.HexColor("#F4F4F6")

# ReportLab has no currency support; the rupee sign is not in Helvetica's
# built-in encoding, so amounts are written as "Rs." to stay legible.
CURRENCY = "Rs."

STATUS_LABELS = {
    AttendanceStatus.PRESENT: "Present",
    AttendanceStatus.HALF_DAY: "Half day",
    AttendanceStatus.ABSENT: "Absent",
}

TYPE_LABELS = {
    TransactionType.WAGE: "Wage earned",
    TransactionType.ADVANCE: "Advance given",
    TransactionType.PAYMENT: "Payment settled",
}

# How each transaction type moves the worker's balance.
TYPE_SIGN = {
    TransactionType.WAGE: "+",
    TransactionType.ADVANCE: "-",
    TransactionType.PAYMENT: "-",
}


def _money(value: Decimal) -> str:
    """1234.5 -> 'Rs. 1,234.50'"""
    return f"{CURRENCY} {value:,.2f}"


def _day(value: date_type) -> str:
    return value.strftime("%d %b %Y")


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "title", parent=base["Title"], fontName=FONT_BOLD, fontSize=18,
            textColor=INK, alignment=0, spaceAfter=2,
        ),
        "subtitle": ParagraphStyle(
            "subtitle", parent=base["Normal"], fontName=FONT_REGULAR, fontSize=9,
            textColor=MUTED, spaceAfter=0,
        ),
        "section": ParagraphStyle(
            "section", parent=base["Heading2"], fontName=FONT_BOLD, fontSize=10,
            textColor=MUTED, spaceBefore=14, spaceAfter=6,
        ),
        "cell": ParagraphStyle(
            "cell", parent=base["Normal"], fontName=FONT_REGULAR, fontSize=9,
            textColor=INK, leading=12,
        ),
        "cellRight": ParagraphStyle(
            "cellRight", parent=base["Normal"], fontName=FONT_REGULAR, fontSize=9,
            textColor=INK, leading=12, alignment=TA_RIGHT,
        ),
        "note": ParagraphStyle(
            "note", parent=base["Normal"], fontName=FONT_REGULAR, fontSize=8,
            textColor=MUTED, leading=10,
        ),
    }


def _footer(canvas, doc) -> None:
    """Page number and provenance on every page."""
    canvas.saveState()
    canvas.setFont(FONT_REGULAR, 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(18 * mm, 12 * mm, "Generated by Cashbook")
    canvas.drawRightString(A4[0] - 18 * mm, 12 * mm, f"Page {canvas.getPageNumber()}")
    canvas.setStrokeColor(RULE)
    canvas.setLineWidth(0.5)
    canvas.line(18 * mm, 16 * mm, A4[0] - 18 * mm, 16 * mm)
    canvas.restoreState()


def build_worker_statement(
    *,
    worker: User,
    contractor: Optional[User],
    transactions: list[Transaction],
    attendance: list[Attendance],
    opening_balance: Decimal,
    period: BalanceSummary,
    closing_balance: Decimal,
    start_date: Optional[date_type],
    end_date: date_type,
    generated_on: date_type,
) -> bytes:
    """Render the statement and return the PDF bytes.

    Rows are expected oldest-first: a statement reads forward in time, unlike
    the app's history list which is newest-first.
    """
    style = _styles()
    buffer = BytesIO()

    period_label = (
        f"{_day(start_date)} to {_day(end_date)}" if start_date else f"Up to {_day(end_date)}"
    )

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=22 * mm,
        title=f"Cashbook statement - {worker.name}",
        author="Cashbook",
        subject=f"Statement for {period_label}",
    )

    story: list = []

    # --- header ------------------------------------------------------------
    story.append(Paragraph("Cashbook statement", style["title"]))
    story.append(Paragraph(period_label, style["subtitle"]))
    story.append(Spacer(1, 10))

    details = [
        ["Worker", worker.name],
        # Nullable — reportlab renders a bare None as the literal "None".
        ["Phone", worker.phone or "Not set"],
        ["Day rate", _money(worker.daily_wage) if worker.daily_wage is not None else "Not set"],
        ["Contractor", contractor.name if contractor else "-"],
        ["Generated", _day(generated_on)],
    ]
    detail_table = Table(details, colWidths=[28 * mm, None], hAlign="LEFT")
    detail_table.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (0, -1), FONT_REGULAR),
                ("FONTNAME", (1, 0), (1, -1), FONT_BOLD),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("TEXTCOLOR", (0, 0), (0, -1), MUTED),
                ("TEXTCOLOR", (1, 0), (1, -1), INK),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("LEFTPADDING", (0, 0), (0, -1), 0),
            ]
        )
    )
    story.append(detail_table)

    # --- the balance, which is the point of the document -------------------
    owed = closing_balance >= 0
    summary_rows = [
        ["Opening balance", _money(opening_balance)],
        ["Wages earned in period", _money(period.total_wages)],
        ["Advances taken in period", "- " + _money(period.total_advances)],
        ["Payments received in period", "- " + _money(period.total_payments)],
        [
            "Closing balance" if owed else "Advance outstanding",
            _money(abs(closing_balance)),
        ],
    ]
    summary = Table(summary_rows, colWidths=[None, 42 * mm], hAlign="LEFT")
    summary.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, -2), FONT_REGULAR),
                ("FONTNAME", (0, -1), (-1, -1), FONT_BOLD),
                ("FONTSIZE", (0, 0), (-1, -1), 9.5),
                ("FONTSIZE", (0, -1), (-1, -1), 11),
                ("ALIGN", (1, 0), (1, -1), "RIGHT"),
                ("TEXTCOLOR", (0, 0), (-1, -2), INK),
                ("TEXTCOLOR", (0, -1), (-1, -1), POSITIVE if owed else NEGATIVE),
                ("LINEABOVE", (0, -1), (-1, -1), 0.75, RULE),
                ("LINEBELOW", (0, 0), (-1, 0), 0.5, RULE),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (0, -1), 0),
            ]
        )
    )
    story.append(Spacer(1, 12))
    story.append(summary)
    story.append(
        Paragraph(
            "Closing balance is what the contractor still owes on the last day of this "
            "period. A negative figure means the worker has drawn more than they have earned."
            if owed
            else "The worker has been paid more than they have earned to date.",
            style["note"],
        )
    )

    # --- transactions ------------------------------------------------------
    story.append(Paragraph("CASH ENTRIES", style["section"]))
    if transactions:
        head = ["Date", "Entry", "Note", "Amount"]
        body = [
            [
                Paragraph(_day(tx.date), style["cell"]),
                Paragraph(TYPE_LABELS[tx.type], style["cell"]),
                Paragraph(tx.note or "-", style["note"]),
                Paragraph(f"{TYPE_SIGN[tx.type]} {_money(tx.amount)}", style["cellRight"]),
            ]
            for tx in transactions
        ]
        story.append(_grid([head] + body, [24 * mm, 34 * mm, None, 32 * mm]))
    else:
        story.append(Paragraph("No cash entries in this period.", style["note"]))

    # --- attendance --------------------------------------------------------
    counts = {status: 0 for status in AttendanceStatus}
    for record in attendance:
        counts[record.status] += 1
    # A half day is half a day worked; absences are not.
    days_worked = counts[AttendanceStatus.PRESENT] + Decimal("0.5") * counts[
        AttendanceStatus.HALF_DAY
    ]

    story.append(Paragraph("ATTENDANCE", style["section"]))
    if attendance:
        story.append(
            Paragraph(
                f"{counts[AttendanceStatus.PRESENT]} present, "
                f"{counts[AttendanceStatus.HALF_DAY]} half day, "
                f"{counts[AttendanceStatus.ABSENT]} absent "
                f"- {days_worked:g} days worked.",
                style["note"],
            )
        )
        story.append(Spacer(1, 6))
        head = ["Date", "Status", "Note"]
        body = [
            [
                Paragraph(_day(record.date), style["cell"]),
                Paragraph(STATUS_LABELS[record.status], style["cell"]),
                Paragraph(record.note or "-", style["note"]),
            ]
            for record in attendance
        ]
        story.append(_grid([head] + body, [24 * mm, 34 * mm, None]))
    else:
        story.append(Paragraph("No attendance recorded in this period.", style["note"]))

    story.append(Spacer(1, 14))
    story.append(
        KeepTogether(
            Paragraph(
                "This statement is generated from the Cashbook ledger and reflects entries "
                "recorded up to the generation date.",
                style["note"],
            )
        )
    )

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


def _grid(rows: list[list], widths: list) -> Table:
    """A table styled to repeat its header when it spills onto the next page."""
    table = Table(rows, colWidths=widths, repeatRows=1, hAlign="LEFT")
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), ACCENT),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), FONT_BOLD),
                ("FONTSIZE", (0, 0), (-1, 0), 8.5),
                ("ALIGN", (-1, 0), (-1, 0), "RIGHT"),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, BAND]),
                ("GRID", (0, 0), (-1, -1), 0.25, RULE),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 5),
                ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    return table


def build_business_report(
    *,
    contractor: User,
    summary: CashSummary,
    crew: list[tuple[User, Decimal, Decimal]],
    cash_entries: list[CashEntry],
    by_category: list[CategoryTotal],
    start_date: Optional[date_type],
    end_date: date_type,
    generated_on: date_type,
) -> bytes:
    """The whole job on paper: what came in, what went out, and to whom.

    `crew` is (worker, days worked, balance owed) per worker, and `cash_entries`
    are the general expenses and receipts, oldest first. The worker statement
    above answers "what do I owe this person"; this one answers "where did the
    money go".
    """
    style = _styles()
    buffer = BytesIO()

    period_label = (
        f"{_day(start_date)} to {_day(end_date)}" if start_date else f"Up to {_day(end_date)}"
    )

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=22 * mm,
        title=f"Cashbook report - {contractor.name}",
        author="Cashbook",
        subject=f"Business report for {period_label}",
    )

    story: list = []
    story.append(Paragraph("Cashbook report", style["title"]))
    story.append(Paragraph(f"{contractor.name} | {period_label}", style["subtitle"]))
    story.append(Spacer(1, 10))

    # --- the cash position -------------------------------------------------
    in_credit = summary.balance >= 0
    money_rows = [
        ["Cash received", _money(summary.cash_in)],
        ["Wages and advances paid", "- " + _money(summary.wages_paid)],
        ["Materials and expenses", "- " + _money(summary.expenses_paid)],
        ["Cash in hand" if in_credit else "Overspent by", _money(abs(summary.balance))],
    ]
    money = Table(money_rows, colWidths=[None, 42 * mm], hAlign="LEFT")
    money.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, -2), FONT_REGULAR),
                ("FONTNAME", (0, -1), (-1, -1), FONT_BOLD),
                ("FONTSIZE", (0, 0), (-1, -1), 9.5),
                ("FONTSIZE", (0, -1), (-1, -1), 11),
                ("ALIGN", (1, 0), (1, -1), "RIGHT"),
                ("TEXTCOLOR", (0, 0), (-1, -2), INK),
                ("TEXTCOLOR", (0, -1), (-1, -1), POSITIVE if in_credit else NEGATIVE),
                ("LINEABOVE", (0, -1), (-1, -1), 0.75, RULE),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (0, -1), 0),
            ]
        )
    )
    story.append(money)
    story.append(
        Paragraph(
            "Wages paid counts advances and settlements - cash that actually changed "
            f"hands. Wages earned in this period were {_money(summary.wages_earned)}, of "
            f"which {_money(summary.outstanding_payable)} is still owed to the crew "
            "across all time.",
            style["note"],
        )
    )

    # --- where it went -----------------------------------------------------
    story.append(Paragraph("BY CATEGORY", style["section"]))
    if by_category:
        head = ["Category", "Direction", "Total"]
        body = [
            [
                Paragraph(item.name, style["cell"]),
                Paragraph("Received" if item.direction.value == "in" else "Spent", style["cell"]),
                Paragraph(_money(item.total), style["cellRight"]),
            ]
            for item in by_category
        ]
        story.append(_grid([head] + body, [None, 34 * mm, 32 * mm]))
    else:
        story.append(Paragraph("No categorised entries in this period.", style["note"]))

    # --- the crew ----------------------------------------------------------
    story.append(Paragraph("CREW", style["section"]))
    if crew:
        head = ["Worker", "Day rate", "Days worked", "Balance"]
        body = [
            [
                Paragraph(worker.name, style["cell"]),
                Paragraph(
                    _money(worker.daily_wage) if worker.daily_wage is not None else "-",
                    style["cellRight"],
                ),
                Paragraph(f"{days:g}", style["cellRight"]),
                Paragraph(_money(balance), style["cellRight"]),
            ]
            for worker, days, balance in crew
        ]
        story.append(_grid([head] + body, [None, 30 * mm, 26 * mm, 32 * mm]))
        story.append(
            Paragraph(
                "Balance is what is still owed to each worker across all time. A negative "
                "figure means they have drawn more than they have earned.",
                style["note"],
            )
        )
    else:
        story.append(Paragraph("No workers on the crew yet.", style["note"]))

    # --- the entries themselves --------------------------------------------
    story.append(Paragraph("EXPENSES AND RECEIPTS", style["section"]))
    if cash_entries:
        head = ["Date", "Category", "Note", "Amount"]
        body = [
            [
                Paragraph(_day(entry.date), style["cell"]),
                Paragraph(entry.category.name if entry.category else "Uncategorised", style["cell"]),
                Paragraph(entry.note or "-", style["note"]),
                Paragraph(
                    ("+ " if entry.direction.value == "in" else "- ") + _money(entry.amount),
                    style["cellRight"],
                ),
            ]
            for entry in cash_entries
        ]
        story.append(_grid([head] + body, [24 * mm, 34 * mm, None, 32 * mm]))
    else:
        story.append(Paragraph("No expenses or receipts in this period.", style["note"]))

    story.append(Spacer(1, 14))
    story.append(
        KeepTogether(
            Paragraph(
                "Generated from the Cashbook ledger. Worker wages are recorded per worker; "
                "everything else is recorded against the categories above.",
                style["note"],
            )
        )
    )

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


def build_invoice(
    *,
    invoice: Invoice,
    site: Site,
    contractor: User,
    preview: Optional[InvoicePreview],
    generated_on: date_type,
) -> bytes:
    """The bill itself: who is being asked for what, and on what basis.

    `total_amount` is printed as the amount due, NOT the sum of the lines
    below it. The two can differ — markup, retention, a rounding, a discount
    agreed on the phone — and the invoice states the figure that was agreed.
    When they differ the breakdown is labelled as a basis rather than a
    tally, so the page never looks like it failed to add up.

    `preview` is optional because an invoice raised months ago can still be
    reprinted after its window has been recomputed away; without it the page
    is the header, the amount and the terms, which is a complete invoice.
    """
    style = _styles()
    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=22 * mm,
        title=f"Invoice {invoice.id} - {invoice.client_name}",
        author="Cashbook",
        subject=f"Invoice for {site.name}",
    )

    story: list = []
    story.append(Paragraph(f"Invoice #{invoice.id}", style["title"]))
    story.append(
        Paragraph(
            f"{contractor.name} | Raised {_day(invoice.created_at.date())} | "
            f"Status: {invoice.status.value.title()}",
            style["subtitle"],
        )
    )
    story.append(Spacer(1, 12))

    # --- who and what ------------------------------------------------------
    address = site.address or "Address not recorded"
    parties = Table(
        [
            [
                Paragraph("<b>Billed to</b>", style["cell"]),
                Paragraph("<b>Site</b>", style["cell"]),
            ],
            [
                Paragraph(invoice.client_name, style["cell"]),
                Paragraph(f"{site.name}<br/>{address}", style["cell"]),
            ],
        ],
        colWidths=[None, None],
        hAlign="LEFT",
    )
    parties.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (0, -1), 0),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("LINEBELOW", (0, 0), (-1, 0), 0.5, RULE),
            ]
        )
    )
    story.append(parties)

    # --- the amount due ----------------------------------------------------
    story.append(Paragraph("AMOUNT DUE", style["section"]))
    due = Table(
        [["Total payable", _money(invoice.total_amount)]],
        colWidths=[None, 46 * mm],
        hAlign="LEFT",
    )
    due.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, -1), FONT_BOLD),
                ("FONTSIZE", (0, 0), (-1, -1), 13),
                ("ALIGN", (1, 0), (1, -1), "RIGHT"),
                ("TEXTCOLOR", (0, 0), (-1, -1), ACCENT),
                ("LINEABOVE", (0, 0), (-1, 0), 0.75, RULE),
                ("LINEBELOW", (0, 0), (-1, 0), 0.75, RULE),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("LEFTPADDING", (0, 0), (0, -1), 0),
            ]
        )
    )
    story.append(due)

    # --- what it was based on ----------------------------------------------
    if preview and preview.lines:
        period = (
            f"{_day(preview.start_date)} to {_day(preview.end_date)}"
            if preview.start_date
            else f"Up to {_day(preview.end_date)}"
        )
        story.append(Paragraph("BASIS OF THIS BILL", style["section"]))
        story.append(
            Paragraph(
                f"Work and costs recorded at {site.name} for {period}.",
                style["note"],
            )
        )
        story.append(Spacer(1, 6))

        head = ["Item", "Quantity", "Rate", "Amount"]
        body = [
            [
                Paragraph(line.label, style["cell"]),
                Paragraph(
                    f"{line.quantity:,.2f} {line.unit or ''}".strip()
                    if line.quantity is not None
                    else "-",
                    style["cell"],
                ),
                Paragraph(
                    _money(line.rate) if line.rate is not None else "-", style["cellRight"]
                ),
                Paragraph(_money(line.amount), style["cellRight"]),
            ]
            for line in preview.lines
        ]
        story.append(_grid([head] + body, [None, 30 * mm, 28 * mm, 30 * mm]))
        story.append(Spacer(1, 6))

        recorded = Table(
            [["Recorded cost of the period", _money(preview.suggested_total)]],
            colWidths=[None, 46 * mm],
            hAlign="LEFT",
        )
        recorded.setStyle(
            TableStyle(
                [
                    ("FONTNAME", (0, 0), (-1, -1), FONT_REGULAR),
                    ("FONTSIZE", (0, 0), (-1, -1), 9.5),
                    ("ALIGN", (1, 0), (1, -1), "RIGHT"),
                    ("TEXTCOLOR", (0, 0), (-1, -1), MUTED),
                    ("LEFTPADDING", (0, 0), (0, -1), 0),
                ]
            )
        )
        story.append(recorded)

        if preview.suggested_total != invoice.total_amount:
            story.append(
                Paragraph(
                    "The amount due above is the figure agreed with the client. The "
                    "breakdown is the recorded basis for it, not a tally of it.",
                    style["note"],
                )
            )

    if invoice.note:
        story.append(Paragraph("NOTE", style["section"]))
        story.append(Paragraph(invoice.note, style["cell"]))

    story.append(Spacer(1, 14))
    story.append(
        KeepTogether(
            Paragraph(
                f"Generated from the Cashbook ledger on {_day(generated_on)}. "
                "Please quote the invoice number above when paying.",
                style["note"],
            )
        )
    )

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


